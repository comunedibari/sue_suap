CREATE TABLE pratiche_eventi ( id int,
id_pratica_evento int NOT NULL AUTO_INCREMENT,
id_pratica int DEFAULT NULL,
id_evento int DEFAULT NULL,
descrizione_evento varchar(4000) DEFAULT NULL,
data_evento datetime DEFAULT NULL,
id_utente int DEFAULT NULL,
oggetto varchar(4000) DEFAULT NULL,
comunicazione text,
note varchar(4000) DEFAULT NULL,
protocollo varchar(255) DEFAULT NULL,
data_protocollo date DEFAULT NULL,
verso enum('I','O') DEFAULT NULL COMMENT 'I/O',
visibilita_cross enum('S','N') DEFAULT NULL COMMENT 'S/N',
visibilita_utente enum('S','N') DEFAULT NULL,
stato_mail int DEFAULT NULL,
id_recapito_notifica int DEFAULT NULL,
pratica_evento_ref int DEFAULT NULL,
vecchio_protocollo varchar(255) DEFAULT NULL,
data_vecchio_protocollo date DEFAULT NULL)