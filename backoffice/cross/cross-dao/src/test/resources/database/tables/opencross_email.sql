CREATE TABLE email ( id int,
id_email int NOT NULL AUTO_INCREMENT,
id_pratica_evento int NOT NULL,
data_inserimento datetime NOT NULL,
data_aggiornamento datetime DEFAULT NULL,
path_eml text,
id_messaggio varchar(256) DEFAULT NULL,
id_messaggio_pec varchar(256) DEFAULT NULL,
email_destinatario varchar(256) NOT NULL,
corpo_email text,
oggetto_email text,
oggetto_risposta text,
corpo_risposta text,
stato int DEFAULT '1',
gruppo int DEFAULT NULL,
tipo_destinazione varchar(45) DEFAULT 'SCONOSCIUTA')